/** Normalisiert für den Vergleich: Kleinbuchstaben, Leerzeichen weg. */
function norm(value) {
  return String(value ?? '').toLowerCase().replace(/[\s\-_·（）()]/g, '');
}

/**
 * Sucht ein Mittel im Katalog.
 * Reihenfolge: exakter Name → Alias exakt → Name enthält Suchbegriff →
 * Suchbegriff enthält Namen („泰诺林片" findet „泰诺林").
 * @param {string} query
 * @returns {object|null}
 */
export function lookupDrug(query) {
  const q = norm(query);
  if (!q) return null;

  const exact = DRUG_CATALOG.find((d) => norm(d.name) === q || (d.aliases || []).some((a) => norm(a) === q));
  if (exact) return exact;

  const contains = DRUG_CATALOG.find(
    (d) => norm(d.name).includes(q) || (d.aliases || []).some((a) => norm(a).includes(q))
  );
  if (contains) return contains;

  // Umgekehrt: Suchbegriff ist länger („布洛芬缓释胶囊" vs. „布洛芬").
  return DRUG_CATALOG.find(
    (d) => q.includes(norm(d.name)) || (d.aliases || []).some((a) => a && q.includes(norm(a)))
  ) || null;
}

/** Katalog-Eintrag in die Form der Beipackzettel-Felder bringen. */
export function catalogToLeaflet(entry) {
  if (!entry) return null;
  return {
    name: entry.name,
    category: entry.category || 'other',
    form: entry.forms || null,
    efficacy: entry.efficacy || null,
    indications: entry.indications || null,
    usage_text: entry.usage || null,
    cautions: entry.cautions || null,
    info_source: 'builtin',
  };
}
