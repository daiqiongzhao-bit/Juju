/**
 * 测试：备份密钥文件闭环（server/services/backup-secrets.js）
 *
 * 覆盖：内容格式校验（合法/缺失键/畸形行/非法键名/空值/控制字符/超大/注释）、
 *       解析、暂存文件 0600、原子写回（含 .pre-restore- 备份与 0600 权限）、
 *       回滚、环境变量快照与还原、应用到运行时环境。
 *
 * 隔离：JUJU_SECRETS_FILE 指向临时目录，全部文件在 test.after 中清理。
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {
  SECRETS_ENTRY_NAME,
  REQUIRED_KEYS,
  secretsPath,
  secretsAvailable,
  readSecretsBuffer,
  validateSecretsContent,
  parseSecrets,
  stageSecretsFile,
  restoreSecretsFile,
  rollbackSecretsFile,
  snapshotEnv,
  restoreEnvSnapshot,
  applySecretsToEnv,
  getSecretsStatus,
} from '../server/services/backup-secrets.js';

const workDir = fs.mkdtempSync(path.join(os.tmpdir(), 'juju-secrets-test-'));
const secretsFile = path.join(workDir, '.juju-secrets');

/** 一份合法的密钥文件内容（含注释与空行，模拟真实文件）。 */
const VALID_CONTENT = [
  '# generated by entrypoint.sh',
  'DB_ENCRYPTION_KEY=00112233445566778899aabbccddeeff',
  '',
  'JUJU_SM4_KEY=0123456789abcdef0123456789abcdef',
  'SESSION_SECRET=deadbeefdeadbeefdeadbeefdeadbeef',
  '',
].join('\n');

process.env.JUJU_SECRETS_FILE = secretsFile;

/**
 * 读取文件权限位（低 9 位）。
 * @param {string} file
 * @returns {number}
 */
function modeOf(file) {
  return fs.statSync(file).mode & 0o777;
}

test('常量：必备键与包内条目名', () => {
  assert.deepEqual(REQUIRED_KEYS, ['DB_ENCRYPTION_KEY', 'JUJU_SM4_KEY', 'SESSION_SECRET']);
  assert.equal(SECRETS_ENTRY_NAME, '.juju-secrets');
});

test('secretsPath: 默认 /data/.juju-secrets，可被 JUJU_SECRETS_FILE 覆盖', () => {
  assert.equal(secretsPath(), secretsFile);

  const saved = process.env.JUJU_SECRETS_FILE;
  try {
    delete process.env.JUJU_SECRETS_FILE;
    assert.equal(secretsPath(), '/data/.juju-secrets');
  } finally {
    process.env.JUJU_SECRETS_FILE = saved;
  }
});

test('validateSecretsContent: 合法文件通过，注释与空行被忽略', () => {
  const result = validateSecretsContent(VALID_CONTENT);
  assert.equal(result.ok, true);
  assert.equal(result.error, null);
  for (const key of REQUIRED_KEYS) assert.ok(result.keys.includes(key));

  // Buffer 入参与字符串入参行为一致。
  assert.deepEqual(validateSecretsContent(Buffer.from(VALID_CONTENT, 'utf8')).ok, true);
  // CRLF：当前实现把 CR(0x0d) 也计入控制字符，因此 CRLF 文件会被拒绝。
  // 这里固化现状——若日后放宽该规则，请同步调整本用例。
  assert.equal(validateSecretsContent(VALID_CONTENT.replace(/\n/g, '\r\n')).ok, false);
});

test('validateSecretsContent: 各种非法输入都被拒绝并给出原因', () => {
  assert.match(validateSecretsContent('').error, /empty/);
  assert.match(validateSecretsContent('   \n  ').error, /empty/);

  const missing = validateSecretsContent('DB_ENCRYPTION_KEY=aa\nJUJU_SM4_KEY=bb');
  assert.equal(missing.ok, false);
  assert.match(missing.error, /missing: SESSION_SECRET/);

  const malformed = validateSecretsContent('DB_ENCRYPTION_KEY=aa\nthis-line-has-no-separator\n');
  assert.equal(malformed.ok, false);
  assert.match(malformed.error, /Malformed line/);

  const badKey = validateSecretsContent('db_key=aa\nJUJU_SM4_KEY=bb\nSESSION_SECRET=cc');
  assert.equal(badKey.ok, false);
  assert.match(badKey.error, /Invalid key name/);

  const emptyValue = validateSecretsContent('DB_ENCRYPTION_KEY=\nJUJU_SM4_KEY=bb\nSESSION_SECRET=cc');
  assert.equal(emptyValue.ok, false);
  assert.match(emptyValue.error, /Empty value/);

  const control = validateSecretsContent(`DB_ENCRYPTION_KEY=a\u0001a\nJUJU_SM4_KEY=bb\nSESSION_SECRET=cc`);
  assert.equal(control.ok, false);
  assert.match(control.error, /control characters/);

  const huge = `DB_ENCRYPTION_KEY=aa\nJUJU_SM4_KEY=bb\nSESSION_SECRET=cc\n# ${'x'.repeat(70000)}`;
  assert.equal(validateSecretsContent(huge).ok, false);
  assert.match(validateSecretsContent(huge).error, /implausibly large/);
});

test('parseSecrets: 正确提取键值对，忽略注释与畸形行', () => {
  const values = parseSecrets(VALID_CONTENT);
  assert.equal(values.DB_ENCRYPTION_KEY, '00112233445566778899aabbccddeeff');
  assert.equal(values.JUJU_SM4_KEY, '0123456789abcdef0123456789abcdef');
  assert.equal(values.SESSION_SECRET, 'deadbeefdeadbeefdeadbeefdeadbeef');
  assert.equal(Object.keys(values).length, 3);

  assert.deepEqual(parseSecrets(''), {});
  assert.deepEqual(parseSecrets('# only a comment'), {});
});

test('stageSecretsFile: 落到指定目录且权限为 0600', async () => {
  const dir = path.join(workDir, 'staging');
  const staged = await stageSecretsFile(VALID_CONTENT, dir);

  assert.ok(fs.existsSync(staged));
  assert.equal(modeOf(staged), 0o600, '暂存密钥文件必须 0600');
  assert.equal(fs.readFileSync(staged, 'utf8'), VALID_CONTENT);

  // 未指定目录时落到系统临时目录。
  const defaultStaged = await stageSecretsFile(VALID_CONTENT);
  assert.equal(modeOf(defaultStaged), 0o600);
  fs.rmSync(defaultStaged, { force: true });
});

test('restoreSecretsFile: 原子写回 0600 并保留 .pre-restore- 备份', async () => {
  fs.writeFileSync(secretsFile, 'DB_ENCRYPTION_KEY=old\nJUJU_SM4_KEY=old\nSESSION_SECRET=old\n', { mode: 0o600 });

  const result = await restoreSecretsFile(Buffer.from(VALID_CONTENT, 'utf8'));
  assert.equal(result.path, secretsFile);
  assert.ok(result.previousBackup, '存在旧文件时应先备份');
  assert.ok(result.previousBackup.includes('.pre-restore-'));
  assert.ok(fs.existsSync(result.previousBackup));
  assert.equal(modeOf(result.previousBackup), 0o600);

  assert.equal(fs.readFileSync(secretsFile, 'utf8'), VALID_CONTENT);
  assert.equal(modeOf(secretsFile), 0o600, '写回后权限必须是 0600');

  // 原子写的中间产物不应残留。
  const leftovers = fs.readdirSync(workDir).filter((name) => name.includes('.tmp-'));
  assert.deepEqual(leftovers, []);
});

test('restoreSecretsFile: 未通过校验的内容一律拒绝（不落盘）', async () => {
  const before = fs.readFileSync(secretsFile, 'utf8');
  await assert.rejects(
    () => restoreSecretsFile('DB_ENCRYPTION_KEY=only-one-key'),
    /Secrets file rejected/
  );
  assert.equal(fs.readFileSync(secretsFile, 'utf8'), before, '拒绝时磁盘内容必须不变');
});

test('rollbackSecretsFile: 恢复旧内容 / 原文件不存在则删除', async () => {
  const previous = Buffer.from('DB_ENCRYPTION_KEY=prev\nJUJU_SM4_KEY=prev\nSESSION_SECRET=prev\n', 'utf8');

  await rollbackSecretsFile(previous);
  assert.equal(fs.readFileSync(secretsFile, 'utf8'), previous.toString('utf8'));
  assert.equal(modeOf(secretsFile), 0o600);

  await rollbackSecretsFile(null);
  assert.equal(fs.existsSync(secretsFile), false);

  await rollbackSecretsFile(Buffer.alloc(0));
  assert.equal(fs.existsSync(secretsFile), false);
});

test('readSecretsBuffer / secretsAvailable: 缺失文件返回空缓冲而不是抛错', async () => {
  fs.rmSync(secretsFile, { force: true });

  assert.equal(await secretsAvailable(), false);
  assert.equal((await readSecretsBuffer()).length, 0);

  fs.writeFileSync(secretsFile, VALID_CONTENT, { mode: 0o600 });
  assert.equal(await secretsAvailable(), true);
  assert.equal((await readSecretsBuffer()).toString('utf8'), VALID_CONTENT);
});

test('getSecretsStatus: 只暴露路径与键名，不暴露值', async () => {
  const status = await getSecretsStatus();
  assert.equal(status.path, secretsFile);
  assert.equal(status.available, true);
  assert.deepEqual(status.keys.sort(), [...REQUIRED_KEYS].sort());

  const dump = JSON.stringify(status);
  assert.ok(!dump.includes('00112233445566778899aabbccddeeff'), '状态里不得出现密钥值');
});

test('snapshotEnv / restoreEnvSnapshot: 完整还原三个键', () => {
  const saved = {};
  for (const key of REQUIRED_KEYS) saved[key] = process.env[key];

  process.env.DB_ENCRYPTION_KEY = 'snap-db';
  process.env.JUJU_SM4_KEY = 'snap-sm4';
  process.env.SESSION_SECRET = 'snap-session';
  const snapshot = snapshotEnv();

  process.env.DB_ENCRYPTION_KEY = 'changed';
  process.env.JUJU_SM4_KEY = 'changed';
  process.env.SESSION_SECRET = 'changed';

  const restored = restoreEnvSnapshot(snapshot);
  assert.deepEqual(restored.sort(), [...REQUIRED_KEYS].sort());
  assert.equal(process.env.DB_ENCRYPTION_KEY, 'snap-db');
  assert.equal(process.env.JUJU_SM4_KEY, 'snap-sm4');
  assert.equal(process.env.SESSION_SECRET, 'snap-session');

  // 快照里为 undefined 的键，还原时必须被删除而不是设为空串。
  const emptySnapshot = { DB_ENCRYPTION_KEY: undefined, JUJU_SM4_KEY: undefined, SESSION_SECRET: undefined };
  restoreEnvSnapshot(emptySnapshot);
  for (const key of REQUIRED_KEYS) assert.equal(key in process.env, false);

  for (const key of REQUIRED_KEYS) {
    if (saved[key] === undefined) delete process.env[key];
    else process.env[key] = saved[key];
  }
});

test('applySecretsToEnv: 把文件内容写进 process.env', () => {
  const applied = applySecretsToEnv(VALID_CONTENT);
  assert.deepEqual(applied.sort(), [...REQUIRED_KEYS].sort());
  assert.equal(process.env.DB_ENCRYPTION_KEY, '00112233445566778899aabbccddeeff');
  assert.equal(process.env.JUJU_SM4_KEY, '0123456789abcdef0123456789abcdef');
  assert.equal(process.env.SESSION_SECRET, 'deadbeefdeadbeefdeadbeefdeadbeef');
});

test.after(() => {
  delete process.env.JUJU_SECRETS_FILE;
  fs.rmSync(workDir, { recursive: true, force: true });
});
